def is_shaped(comp: Component) -> bool:
    """True when *comp* has a body that a fill colour / line style applies to."""
    return isinstance(comp, DrawingComponent) or comp.kind in SHAPED_KINDS


def symbol_style(comp: Component) -> tuple[str, str, str]:
    """``(line_style, line_color, fill_color)`` in effect for a circuit symbol.

    Line style and colour apply to every symbol; the fill only to a shaped one, so
    a stale fill on a resistor (e.g. from a hand-edited file) is ignored consistently
    by codegen and canvas. Empty string = unset.
    """
    fill = getattr(comp, "fill_color", "") if is_shaped(comp) else ""
    return getattr(comp, "line_style", ""), getattr(comp, "line_color", ""), fill
