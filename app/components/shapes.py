def style_capabilities(comp: Component) -> tuple[bool, bool, bool]:
    """Whether line style, line colour and body fill apply, in that order."""
    if isinstance(comp, DrawingComponent):
        supported = isinstance(comp, StyledComponent)
        return supported, supported, supported
    definition = REGISTRY.get(comp.kind)
    kind = (definition.base_kind if definition else None) or comp.kind
    return kind in DASHABLE_KINDS, kind in COLORABLE_KINDS, kind in FILLABLE_KINDS


def symbol_style(comp: Component) -> tuple[str, str, str]:
    """Effective line style, line colour and body fill for export and canvas."""
    dash, color, fill = style_capabilities(comp)
    return (getattr(comp, "line_style", "") if dash else "",
            getattr(comp, "line_color", "") if color else "",
            getattr(comp, "fill_color", "") if fill else "")
