"""Which circuit symbols have a *body* (a box, triangle, circle...) that can be filled.

A component with a body gets the full "Fill & line style" inspector section (line
style, line colour, fill); every other symbol (resistor, capacitor, ground, ...)
gets the same section without **Fill** (there is no body to fill). A resistor is
never "shaped", even when the document draws resistors European (box) style, which
keeps it visually distinct from a fuse. Block components (rect / circle / bipole box) are always
shaped. This module is the single source of truth: the code generator, the canvas
painter and the inspector all go through :func:`symbol_style` / :func:`is_shaped`,
so what is emitted, drawn and offered can never disagree.

``SHAPED_KINDS`` is derived, not hand-written: ``scripts/find_fillable_kinds.py``
renders every kind with ``fill=`` in CircuiTikZ and keeps those where the fill paints
a compact region (CircuiTikZ also fills capacitor plates, but they are slivers, not
an enclosed shape). Re-run it after regenerating the component library and paste the
printed set here. A kind missing from the set simply gets colour-only styling, which
is the safe default (user-captured custom components are in that case).
"""

